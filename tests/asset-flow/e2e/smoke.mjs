// Smoke for AF1 (Playwright, not the grader): PW_DIR=<dir with node_modules/playwright> SHOTS=<dir> node tests/asset-flow/e2e/smoke.mjs
import { createRequire } from 'module';
import path from 'path';
import { fileURLToPath } from 'url';
const require = createRequire((process.env.PW_DIR || path.dirname(fileURLToPath(import.meta.url))) + '/');
const { chromium } = require('playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../prototype/v4');
const shot = process.env.SHOTS || '';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: +(process.env.W || 393), height: 852 }, colorScheme: process.env.SCHEME || 'light' });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto('file://' + root + '/index.html');
await p.waitForTimeout(500);
const out = {};
const txt = async (s) => (await p.locator(s).first().innerText()).replace(/\s+/g, ' ');
const nav = async () => { await p.click('.dk-ft [data-dknav="1"]'); await p.waitForTimeout(80); };
out.main = await txt('[data-testid=cat-house]');
if (shot) await p.screenshot({ path: shot + '/main.png' });
await p.click('[data-testid=add-house]');
await p.waitForTimeout(200);
out.start = await txt('[data-testid=dk-count]');
await p.click('[data-dkpick="Single-family home"]');
await p.waitForTimeout(400);
await p.click('[data-dkpick="Planning to buy"]');
await p.waitForTimeout(400);
await p.fill('[data-dkf="addr:0"]', '7 Maple Ct, Acworth');
await nav();
await nav();
out.atPrice = await txt('#dkcard');
await p.fill('[data-dkf="price:0"]', '239000');
out.strip = await txt('[data-testid=dk-strip]');
if (shot) await p.screenshot({ path: shot + '/deck-price.png' });
await nav();
await p.click('[data-dkpick="Conventional 30-year"]');
await p.waitForTimeout(300);
out.loan = await txt('#dkcard');
if (shot) await p.screenshot({ path: shot + '/deck-loan.png' });
const box = await p.locator('#dkcard').boundingBox();
const before = await txt('[data-testid=dk-count]');
await p.mouse.move(box.x + box.width * 0.8, box.y + 40);
await p.mouse.down();
await p.mouse.move(box.x + 100, box.y + 44, { steps: 8 });
await p.mouse.up();
await p.waitForTimeout(300);
out.swipe = before + ' -> ' + (await txt('[data-testid=dk-count]'));
let n = 0;
while (!(await p.locator('[data-dksave]').count()) && n++ < 40) {
  const nx = p.locator('.dk-ft [data-dknav="1"]');
  if (await nx.count()) await nx.click();
  else await p.locator('[data-dkpick]').first().click();
  await p.waitForTimeout(300);
}
out.review = (await txt('#dkcard')).slice(0, 300);
out.total = await txt('[data-testid=dk-count]');
if (shot) await p.screenshot({ path: shot + '/deck-review.png', fullPage: true });
await p.click('[data-dksave]');
await p.waitForTimeout(400);
out.savedRoute = await p.evaluate(() => location.hash);
await p.goto('file://' + root + '/index.html#');
await p.waitForTimeout(300);
await p.click('[data-testid=view-house]');
await p.waitForTimeout(300);
out.view = (await txt('[data-testid=va-card]')).slice(0, 300);
await p.click('[data-vsort="cf"]');
out.cards = await p.locator('[data-testid=va-card]').count();
if (shot) await p.screenshot({ path: shot + '/view.png', fullPage: true });
console.log(JSON.stringify(out, null, 1));
console.log('errors', errs);
await b.close();
