#!/usr/bin/env python3
"""List hard-coded colors in app CSS and inline styles; write docs/color-inventory.md. Read-only on the app."""
import re, os, glob, collections
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEX = r'#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})(?![0-9a-zA-Z_-])'
FUNC = r'(?:rgba?|hsla?)\([^)]*\)'
COL = re.compile(r'(?<![\w&/#"])(?:%s)|%s' % (HEX, FUNC))
NAMED = re.compile(r'(?<![\w.#-])(?:color|background(?:-color)?|border(?:-[a-z]+)?|fill|stroke|outline)\s*:\s*(white|black)\b')
LEGACY = {'bg': 'bg', 'card': 'surface', 'ink': 'text', 'mut': 'textMuted', 'line': 'border', 'acc': 'accent', 'ok': 'good',
          'warn': 'warn', 'bad': 'bad', 'bar': 'surface2', 'field': 'surface2', 'flash': 'NEW (highlight)'}
VARS = '|'.join(LEGACY)


def norm(v):
    v = v.lower()
    if v.startswith('#') and len(v) in (4, 5):
        v = '#' + ''.join(c * 2 for c in v[1:])
    return v


def strip_data(s):
    return re.sub(r'data:[^)"\'\s]{40,}', 'data:...', s)


def legacy_table(css):
    t = {}
    for m in re.finditer(r'--(%s):\s*(#[0-9a-fA-F]{3,8})' % VARS, css):
        t.setdefault(norm(m.group(2)), m.group(1))
    return t


def suggest(val, line, table):
    v = norm(val)
    m = re.search(r'--(%s):\s*%s' % (VARS, re.escape(val)), line)
    if m:
        return 'definition of legacy var(--%s) -> supply from --th-%s' % (m.group(1), LEGACY[m.group(1)])
    if v in table:
        return 'same value as var(--%s) -> --th-%s' % (table[v], LEGACY[table[v]])
    if v in ('#fff', '#ffffff', 'white'):
        return '--th-on-accent (on accent fill) or --th-surface'
    if v in ('#000', '#000000', 'black'):
        return '--th-text, or color-mix(in srgb, var(--th-text) N%, transparent) for shadows'
    if v.startswith(('rgba', 'hsla')):
        return 'color-mix(in srgb, var(--th-text) N%, transparent) (shadow/scrim)'
    return 'NO MATCHING TOKEN: decide (nearest of text/accent/good/warn/bad, or add a token)'


rows = []


def scan(path, text, kind_fn, table):
    for i, line in enumerate(text.split('\n'), 1):
        line = strip_data(line)
        vals = [m.group(0) for m in COL.finditer(line)] + [m.group(1) for m in NAMED.finditer(line)]
        for v in vals:
            if v.startswith('#') and len(v) <= 5 and not re.search(r'color|style|fill|stroke|background|border|shadow', line, re.I):
                continue  # 3/4-digit hex without a color context is an id/anchor (e.g. "#add")
            rows.append((os.path.relpath(path, R), i, v, kind_fn(line), suggest(v, line, table)))


def collect():
    css_main = open(os.path.join(R, 'prototype/v4/style.css')).read()
    table = legacy_table(css_main)
    css = [os.path.join(R, 'prototype/v4/style.css')] + sorted(glob.glob(os.path.join(R, 'ui/**/*.css'), recursive=True))
    for p in css:
        if os.path.basename(p) == 'themes.css':
            continue  # the token file itself
        scan(p, open(p).read(), lambda l: 'css-var-def' if re.search(r'--(%s):' % VARS, l) else 'css', table)
    for p in sorted(glob.glob(os.path.join(R, 'prototype/v4/src/**/*.*'), recursive=True)):
        if p.endswith(('.js', '.html', '.css')) and os.path.isfile(p):
            scan(p, open(p).read(), lambda l: 'inline-style' if re.search(r'style|cssText|fill|stroke', l) else 'js-literal', table)
    ah = open(os.path.join(R, 'prototype/v4/artifact.html')).read()
    ah = re.sub(r'<style\b.*?</style>|<script\b.*?</script>', lambda m: '\n' * m.group(0).count('\n'), ah, flags=re.S)
    scan(os.path.join(R, 'prototype/v4/artifact.html'), ah, lambda l: 'inline-style (markup)', table)
    return rows


def report(rs):
    byf = collections.OrderedDict()
    for r in rs:
        byf.setdefault(r[0], []).append(r)
    o = ['# Hard-coded color inventory', '',
         'Generated by `scripts/color-inventory.py` (read-only on the app). Scope: `prototype/v4/style.css`, any `ui/**/*.css` (none exist yet; `ui/shared/themes.css` is the token file and is excluded), `prototype/v4/src/**`, and `prototype/v4/artifact.html` outside its bundled `<style>`/`<script>` blocks (those are build copies of style.css and src; base64 data: URIs skipped).',
         '"Should become" names the `--th-*` token from `ui/shared/themes.css`.', '',
         '## Counts', '', '| File | Colors found |', '|---|---|']
    for f, x in byf.items():
        o.append('| %s | %d |' % (f, len(x)))
    o += ['| **Total** | **%d** |' % len(rs), '']
    kinds = collections.Counter(r[3] for r in rs)
    o.append('By kind: ' + ', '.join('%s %d' % kv for kv in sorted(kinds.items())) + '.')
    nm = [r for r in rs if r[4].startswith('NO MATCHING')]
    o += ['', '**Input and select outlines** (`input`/`select`, the `.iw` field box and focus ring) map to `--th-control` (3:1 on bg, surface, surface2), not `--th-border`. Decorative hairlines stay soft and map to `--th-border`.']
    o += ['', 'Needing a decision (no matching token): %d.' % len(nm), '', '## Detail', '']
    for f, x in byf.items():
        o += ['### ' + f, '', '| Line | Value | Kind | Should become |', '|---|---|---|---|']
        for _, ln, v, k, s in x:
            o.append('| %d | `%s` | %s | %s |' % (ln, v.replace('|', '\\|'), k, s))
        o.append('')
    return '\n'.join(o)


if __name__ == '__main__':
    rs = collect()
    out = os.path.join(R, 'docs/color-inventory.md')
    open(out, 'w').write(report(rs))
    print('wrote', out, len(rs), 'colors')
    for f, n in collections.Counter(r[0] for r in rs).items():
        print(n, f)
