'use strict';
// Spec section 2: download sources, compute tables, write data/inflation.json. Failed sources keep
// their last value (from the existing file) and are listed in the PR body text.
const fs = require('fs');
const path = require('path');
const { buildPath } = require('./blend');
const { backtest, bandFromOffsets } = require('./backtest');

const SRC_NAMES = { cleveland: 'Cleveland Fed expected inflation', spf: 'Philadelphia Fed SPF 10-year CPI', treasury: 'Treasury 10-year breakeven', cpi: 'FRED CPIAUCNS (CPI-U all items NSA)' };

// res = result of fetch.fetchAll (or a fixture); prev = previous data/inflation.json or null.
// Returns { json, failures:[string], notes:[string] }.
function assemble(res, prev, today) {
  const failures = [], notes = [];
  const sources = [];
  const prevSrc = n => prev && prev.sources && prev.sources.find(s => s.name === n);
  const keep = (name, why) => { failures.push(`${name}: ${why}`); const p = prevSrc(name); if (p) { sources.push(p); notes.push(`${name}: kept last value (as of ${p.asOf})`); } };

  let inputs = prev && prev.inputs ? JSON.parse(JSON.stringify(prev.inputs)) : {};
  let clevHist = null;
  if (res.cleveland.ok) {
    clevHist = res.cleveland.data;
    const last = clevHist[clevHist.length - 1];
    inputs.cleveland = { asOf: last.month, points: last.points };
    sources.push({ name: SRC_NAMES.cleveland, url: res.cleveland.url, asOf: last.month, value: +(last.points[9] * 100).toFixed(4) });
  } else keep(SRC_NAMES.cleveland, res.cleveland.error);

  if (res.spf.ok) {
    inputs.survey10 = { asOf: res.spf.data.quarter, value: res.spf.data.value / 100 };
    sources.push({ name: SRC_NAMES.spf, url: res.spf.url, asOf: res.spf.data.quarter, value: res.spf.data.value });
  } else keep(SRC_NAMES.spf, res.spf.error);

  if (res.treasury.ok) {
    const t = res.treasury.data, be = t.byMaturity[10];
    sources.push({ name: SRC_NAMES.treasury, url: res.treasury.url, asOf: t.date, value: be ? be.breakeven : null });
  } else keep(SRC_NAMES.treasury, res.treasury.error);

  let cpi = null;
  if (res.cpi.ok) {
    cpi = res.cpi.data;
    const k = Object.keys(cpi).sort().pop();
    sources.push({ name: SRC_NAMES.cpi, url: res.cpi.url, asOf: k, value: cpi[k] });
  } else keep(SRC_NAMES.cpi, res.cpi.error);

  if (!inputs.cleveland || !inputs.survey10) throw new Error('Cannot build: no Cleveland curve or survey value, fresh or kept. Failures: ' + failures.join('; '));

  const path_ = buildPath(inputs.cleveland.points, inputs.survey10.value);

  // band: only from a backtest, never from a guess
  let band = null;
  if (clevHist && res.spfHistory.ok && cpi) {
    try {
      const b = backtest(clevHist, res.spfHistory.data, cpi);
      band = { errLow: b.errLow, errHigh: b.errHigh, cases: b.cases, supported: b.supported, asOf: today };
    } catch (e) { failures.push('Backtest: ' + e.message); }
  } else {
    failures.push('Backtest: skipped, needs Cleveland history, SPF history and CPI' + (res.spfHistory.ok ? '' : ' (SPF history: ' + res.spfHistory.error + ')'));
  }
  if (!band) {
    if (!prev || !prev.band) throw new Error('Cannot build: no backtest and no earlier band. The band is never guessed. Failures: ' + failures.join('; '));
    band = Object.assign({ supported: prev.bandSupported }, prev.band);
    notes.push('Band: kept last good band (backtest of ' + prev.band.asOf + ')');
  }
  const bands = bandFromOffsets(path_.smoothR, band);

  const json = {
    generatedAt: today,
    sources,
    level: path_.level.map(v => +v.toFixed(6)),
    low: bands.low.map(v => +v.toFixed(6)),
    high: bands.high.map(v => +v.toFixed(6)),
    bandSupported: bands.bandSupported,
    adjust: prev && prev.adjust ? prev.adjust : { points: 0, reason: '', date: '', expires: '' },
    inputs,
    band: { errLow: band.errLow.map(v => +v.toFixed(6)), errHigh: band.errHigh.map(v => +v.toFixed(6)), cases: band.cases, asOf: band.asOf },
  };
  return { json, failures, notes };
}

function prBody(r, today) {
  const L = ['Monthly inflation data refresh (' + today + '). Generated by .github/workflows/inflation.yml; review and merge to dev by hand.', ''];
  L.push('## Sources', ...r.json.sources.map(s => `- ${s.name}: ${s.value} as of ${s.asOf}`), '');
  L.push(r.failures.length ? '## SOURCE FAILURES' : '## Source failures: none');
  r.failures.forEach(f => L.push('- ' + f));
  if (r.notes.length) L.push('', '## Kept from last run', ...r.notes.map(n => '- ' + n));
  return L.join('\n') + '\n';
}

async function main() {
  const root = path.resolve(__dirname, '..', '..');
  const file = path.join(root, 'data', 'inflation.json');
  const prev = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : null;
  const today = new Date().toISOString().slice(0, 10);
  const res = await require('./fetch').fetchAll(new Date());
  const r = assemble(res, prev, today);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(r.json) + '\n');
  fs.writeFileSync(process.argv[2] || path.join(root, 'inflation-pr-body.md'), prBody(r, today));
  console.log(prBody(r, today));
}

if (require.main === module) main().catch(e => { console.error(e.message); process.exit(1); });
module.exports = { assemble, prBody };
